export function applyLTFlexibleSourceMode(mode,equipment,{snapshot=false}={}){
 const p=ltFlexibleSource(mode?.weapon_mode_id);
 if(!p||equipment?.source!=='LT'||p.equipmentId!==equipment.equipment_id)return mode;
 const before=p.sourceFieldsBefore;
 if(!p.manualOnly&&(!snapshot||!before||[before.damage,p.stats.damage].includes(mode.raw_calc?.damage))){
  const m=/^(sw|thr)([+-]\d+)?(?:\(([\d.]+)\))?\s+(\S+)$/.exec(p.stats.damage);
  if(!m)throw Error('Invalid verified LT flexible Damage');
  mode.raw_calc={...mode.raw_calc,damage:p.stats.damage};const damage={...mode.stats.damage,st:m[1],type:m[4]};
  if(m[2])damage.base=String(Number(m[2]));else delete damage.base;
  if(m[3])damage.armor_divisor=Number(m[3]);else delete damage.armor_divisor;
  mode.stats.damage=damage;
 }
 for(const [key,field]of [['reach','reach'],['parry','parry'],['strength','st']])
  if(!snapshot||!before||[before[field],p.stats[field]].includes(mode.stats[key]))mode.stats[key]=p.stats[field];
 if(!snapshot||!before||[before.usage,p.usage].includes(mode.usage))mode.usage=p.usage;
 mode.lt_flexible_contract={modelId:p.modelId,part:p.damagePart,hands:p.hands,occupiedHands:p.occupiedHands??p.hands,sourcePages:p.sourcePages};
 if(p.manualOnly)mode.lt_flexible_manual=p.manualHint;
 return mode;
}

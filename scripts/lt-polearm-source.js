function setDamage(mode,expression){
 const m=/^(sw|thr)([+-]\d+)?(?:\(([\d.]+)\))?\s+(\S+)$/.exec(expression);
 if(!m)throw Error('Invalid verified LT polearm Damage');
 mode.raw_calc={...mode.raw_calc,damage:expression};
 const damage={...mode.stats.damage,st:m[1],type:m[4]};
 if(m[2])damage.base=String(Number(m[2]));else delete damage.base;
 if(m[3])damage.armor_divisor=Number(m[3]);else delete damage.armor_divisor;
 mode.stats.damage=damage;
}
export function applyLTPolearmSourceMode(mode,equipment,{snapshot=false}={}){
 const p=ltPolearmSource(mode?.weapon_mode_id);
 if(!p||equipment?.source!=='LT'||equipment.equipment_id!==p.equipmentId)return mode;
 const before=p.sourceFieldsBefore;
 if(!snapshot||!before||[before.damage,p.stats.damage].includes(mode.raw_calc?.damage))setDamage(mode,p.stats.damage);
 for(const [key,field]of [['reach','reach'],['parry','parry'],['strength','st']])
  if(!snapshot||!before||[before[field],p.stats[field]].includes(mode.stats[key]))mode.stats[key]=p.stats[field];
 if(!snapshot||!before||[before.usage,p.usage].includes(mode.usage))mode.usage=p.usage;
 mode.lt_polearm_contract={modelId:p.modelId,sourcePages:p.sourcePages,damagePart:p.damagePart,hands:p.hands,motion:p.motion??null};
 return mode;
}

